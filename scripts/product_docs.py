"""Regenerate the parts of docs/product/ that are read straight from the code, and check the rest is in step.

    python scripts/product_docs.py          # rewrite docs/product/generated/*.md
    python scripts/product_docs.py --check  # exit 1 if they are out of date, or if a page is missing from the sitemap

The generated files are the source of truth for what exists: every route the app serves, every database table
and column, every page of the public site and every scheduled workflow. tests/test_product_docs.py runs --check,
so a new page or endpoint that isn't documented fails the test suite.
"""

from __future__ import annotations

import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "product" / "generated"
SITEMAP = ROOT / "docs" / "product" / "02-sitemap.md"


def routes() -> list[tuple[str, str, str, str]]:
    os.environ.setdefault("APP_ENV", "development")
    sys.path.insert(0, str(ROOT))
    from propelo.cloud.app import create_app
    from propelo.cloud.config import Config
    app = create_app(Config.from_env())
    out = []
    for r in app.routes:
        methods = sorted(getattr(r, "methods", None) or [])
        if not methods:
            continue
        fn = getattr(r, "endpoint", None)
        deps = " ".join(str(getattr(d.call, "__name__", "")) for d in getattr(getattr(r, "dependant", None), "dependencies", []) or [])
        auth = ("staff" if "staff_only" in deps else "admin" if "admin_only" in deps else "session" if "session_only" in deps
                else "account or key" if "principal" in deps or "agent" in deps else "public")
        doc = (fn.__doc__ or "").strip().splitlines()[0] if fn is not None and fn.__doc__ else ""
        for m in methods:
            if m == "HEAD":
                continue
            out.append((r.path, m, auth, doc))
    return sorted(set(out))


def tables() -> dict[str, list[str]]:
    cols: dict[str, list[str]] = {}
    for f in sorted((ROOT / "propelo" / "cloud" / "migrations").glob("*.sql")):
        sql = re.sub(r"--[^\n]*", "", f.read_text(encoding="utf-8"))
        for m in re.finditer(r"CREATE TABLE (\w+)\s*\((.*?)\n\);", sql, re.S):
            names = []
            for line in m.group(2).split("\n"):
                line = line.strip().rstrip(",")
                w = line.split()
                if w and w[0].upper() not in ("PRIMARY", "UNIQUE", "FOREIGN", "CHECK", "CONSTRAINT"):
                    names.append(w[0])
            cols.setdefault(m.group(1), []).extend(names)
        for m in re.finditer(r"ALTER TABLE (\w+) ADD COLUMN (\w+)", sql):
            cols.setdefault(m.group(1), []).append(m.group(2) + f" ({f.stem})")
    return cols


def site_pages() -> list[str]:
    pages = sorted(p.name for p in (ROOT / "website").glob("*.html"))
    return pages + ["jobs.html (generated by propelo/site.py)", "demo/index.html (copy of dashboard/index.html)",
                    "404.html, robots.txt, sitemap.xml, feed.xml, api/jobs*.json (generated)"]


def workflows() -> list[tuple[str, str]]:
    out = []
    for f in sorted((ROOT / ".github" / "workflows").glob("*.yml")):
        t = f.read_text(encoding="utf-8")
        name = (re.search(r"^name:\s*(.+)$", t, re.M) or [None, f.stem])[1]
        crons = re.findall(r'cron:\s*"([^"]+)"', t)
        on = "schedule " + ", ".join(crons) if crons else ""
        trig = [x for x in ("push", "pull_request", "workflow_dispatch", "release") if re.search(rf"^\s+{x}:", t, re.M) or re.search(rf"^on:.*{x}", t, re.M)]
        out.append((f.name, f"{name}: " + ", ".join(filter(None, [on] + trig))))
    return out


def render() -> dict[str, str]:
    rs = routes()
    lines = ["# Routes the app serves (generated)", "", "Generated by `scripts/product_docs.py` from `propelo/cloud/app.py`. Do not edit by hand.", "",
             f"{len(rs)} method and path pairs.", "", "| method | path | who can call it | what it does |", "| --- | --- | --- | --- |"]
    lines += [f"| {m} | `{p}` | {a} | {d.replace('|', '/')} |" for p, m, a, d in rs]
    out = {"routes.md": "\n".join(lines) + "\n"}
    t = tables()
    lines = ["# Database tables (generated)", "", "Generated from `propelo/cloud/migrations/*.sql`. Do not edit by hand.", "",
             f"{len(t)} tables.", ""]
    for name, cols in t.items():
        lines += [f"## {name}", "", ", ".join(f"`{c}`" for c in cols), ""]
    out["database.md"] = "\n".join(lines)
    lines = ["# Public site files and workflows (generated)", "", "## Site pages (website/ and the job board build)", ""]
    lines += [f"- {p}" for p in site_pages()]
    lines += ["", "## GitHub workflows", ""] + [f"- `{f}`: {d}" for f, d in workflows()]
    out["site-and-workflows.md"] = "\n".join(lines) + "\n"
    return out


def page_routes() -> list[str]:
    return sorted({p for p, m, a, d in routes() if m == "GET" and not p.startswith("/api/")})


def main(argv: list[str]) -> int:
    check = "--check" in argv
    files = render()
    bad = []
    for name, text in files.items():
        f = OUT / name
        if check:
            if not f.exists() or f.read_text(encoding="utf-8") != text:
                bad.append(f"docs/product/generated/{name} is out of date: run python scripts/product_docs.py")
        else:
            OUT.mkdir(parents=True, exist_ok=True)
            f.write_text(text, encoding="utf-8")
    sitemap = SITEMAP.read_text(encoding="utf-8") if SITEMAP.exists() else ""
    for p in page_routes():
        if f"`{p}`" not in sitemap:
            bad.append(f"page route {p} is not in docs/product/02-sitemap.md")
    for name in (ROOT / "website").glob("*.html"):
        if name.name not in sitemap:
            bad.append(f"site page {name.name} is not in docs/product/02-sitemap.md")
    for line in bad:
        print(line)
    if not check:
        print(f"wrote {', '.join(files)}")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
